--------------------------------------------------------------------------------
-- crm_sics_oracle.sql
--
-- CRM de Atendimento do SICS — modelo de dados Oracle.
-- Atende usuários internos (secretarias, superintendências) e fornecedores:
-- abre, qualifica, encaminha, resolve e mede chamados.
--
-- 8 tabelas (prefixo CRM_), mais domínio inicial de SLA e filas.
-- Centro do modelo: CRM_CHAMADO -> CONTATO, FILA, ATENDENTE, SLA
--                   CRM_CHAMADO <- INTERACAO, STATUS_HIST, ANEXO
--
-- Alvo: Oracle Database 12c+ (usa IDENTITY e CHECK constraints).
-- Execução sugerida no SQL*Plus / SQLcl:  @crm_sics_oracle.sql
--------------------------------------------------------------------------------

SET DEFINE OFF;

--------------------------------------------------------------------------------
-- 1) CRM_FILA — setor / roteamento
--------------------------------------------------------------------------------
CREATE TABLE CRM_FILA (
    ID            NUMBER GENERATED BY DEFAULT ON NULL AS IDENTITY PRIMARY KEY,
    NOME          VARCHAR2(80)  NOT NULL,
    DESCRICAO     VARCHAR2(400),
    ATIVO         CHAR(1 CHAR)  DEFAULT 'S' NOT NULL,
    CRIADO_EM     TIMESTAMP     DEFAULT SYSTIMESTAMP NOT NULL,
    CONSTRAINT UQ_FILA_NOME  UNIQUE (NOME),
    CONSTRAINT CK_FILA_ATIVO CHECK (ATIVO IN ('S','N'))
);

COMMENT ON TABLE  CRM_FILA           IS 'Filas de roteamento por setor (Compras, Fornecedores, Financeiro, Sistema/TI).';
COMMENT ON COLUMN CRM_FILA.NOME      IS 'Nome da fila/setor.';
COMMENT ON COLUMN CRM_FILA.ATIVO     IS 'S = fila ativa; N = inativa.';

--------------------------------------------------------------------------------
-- 2) CRM_SLA — prazos por prioridade
--------------------------------------------------------------------------------
CREATE TABLE CRM_SLA (
    ID                   NUMBER GENERATED BY DEFAULT ON NULL AS IDENTITY PRIMARY KEY,
    PRIORIDADE           VARCHAR2(20) NOT NULL,
    HORAS_PRIMEIRA_RESP  NUMBER(6,2)  NOT NULL,
    HORAS_RESOLUCAO      NUMBER(6,2)  NOT NULL,
    ATIVO                CHAR(1 CHAR) DEFAULT 'S' NOT NULL,
    CRIADO_EM            TIMESTAMP    DEFAULT SYSTIMESTAMP NOT NULL,
    CONSTRAINT UQ_SLA_PRIORIDADE UNIQUE (PRIORIDADE),
    CONSTRAINT CK_SLA_PRIORIDADE CHECK (PRIORIDADE IN ('BAIXA','MEDIA','ALTA','URGENTE')),
    CONSTRAINT CK_SLA_ATIVO      CHECK (ATIVO IN ('S','N')),
    CONSTRAINT CK_SLA_H1R        CHECK (HORAS_PRIMEIRA_RESP > 0),
    CONSTRAINT CK_SLA_HRES       CHECK (HORAS_RESOLUCAO    > 0)
);

COMMENT ON TABLE  CRM_SLA                     IS 'Prazos de SLA por prioridade (em horas).';
COMMENT ON COLUMN CRM_SLA.HORAS_PRIMEIRA_RESP IS 'Horas para a 1a resposta ao solicitante.';
COMMENT ON COLUMN CRM_SLA.HORAS_RESOLUCAO     IS 'Horas para resolução do chamado.';

--------------------------------------------------------------------------------
-- 3) CRM_CONTATO — quem abre o chamado (interno ou fornecedor)
--------------------------------------------------------------------------------
CREATE TABLE CRM_CONTATO (
    ID                 NUMBER GENERATED BY DEFAULT ON NULL AS IDENTITY PRIMARY KEY,
    TIPO               VARCHAR2(20) NOT NULL,
    NOME               VARCHAR2(200) NOT NULL,
    DOCUMENTO          VARCHAR2(20),
    EMAIL              VARCHAR2(200),
    TELEFONE           VARCHAR2(30),
    ORGAO              VARCHAR2(200),
    CARGO              VARCHAR2(120),
    USUARIO_SICS_REF   VARCHAR2(60),
    FORNECEDOR_REF     VARCHAR2(60),
    ATIVO              CHAR(1 CHAR) DEFAULT 'S' NOT NULL,
    CRIADO_EM          TIMESTAMP    DEFAULT SYSTIMESTAMP NOT NULL,
    CONSTRAINT CK_CONTATO_TIPO  CHECK (TIPO IN ('INTERNO','FORNECEDOR')),
    CONSTRAINT CK_CONTATO_ATIVO CHECK (ATIVO IN ('S','N'))
);

COMMENT ON TABLE  CRM_CONTATO                  IS 'Solicitantes: usuários internos (secretarias/superintendências) e fornecedores.';
COMMENT ON COLUMN CRM_CONTATO.TIPO             IS 'INTERNO ou FORNECEDOR.';
COMMENT ON COLUMN CRM_CONTATO.DOCUMENTO        IS 'CPF/CNPJ ou outro documento.';
COMMENT ON COLUMN CRM_CONTATO.USUARIO_SICS_REF IS 'Vínculo com o cadastro de usuário no SICS.';
COMMENT ON COLUMN CRM_CONTATO.FORNECEDOR_REF   IS 'Vínculo com o cadastro de fornecedor.';

CREATE INDEX IX_CONTATO_DOCUMENTO ON CRM_CONTATO (DOCUMENTO);
CREATE INDEX IX_CONTATO_SICS      ON CRM_CONTATO (USUARIO_SICS_REF);
CREATE INDEX IX_CONTATO_FORNEC    ON CRM_CONTATO (FORNECEDOR_REF);

--------------------------------------------------------------------------------
-- 4) CRM_ATENDENTE — quem resolve
--------------------------------------------------------------------------------
CREATE TABLE CRM_ATENDENTE (
    ID                 NUMBER GENERATED BY DEFAULT ON NULL AS IDENTITY PRIMARY KEY,
    NOME               VARCHAR2(200) NOT NULL,
    EMAIL              VARCHAR2(200) NOT NULL,
    FILA_PRINCIPAL_ID  NUMBER,
    USUARIO_SICS_REF   VARCHAR2(60),
    ATIVO              CHAR(1 CHAR) DEFAULT 'S' NOT NULL,
    CRIADO_EM          TIMESTAMP    DEFAULT SYSTIMESTAMP NOT NULL,
    CONSTRAINT UQ_ATENDENTE_EMAIL UNIQUE (EMAIL),
    CONSTRAINT CK_ATENDENTE_ATIVO CHECK (ATIVO IN ('S','N')),
    CONSTRAINT FK_ATENDENTE_FILA  FOREIGN KEY (FILA_PRINCIPAL_ID)
        REFERENCES CRM_FILA (ID)
);

COMMENT ON TABLE  CRM_ATENDENTE                   IS 'Atendentes que resolvem chamados.';
COMMENT ON COLUMN CRM_ATENDENTE.FILA_PRINCIPAL_ID IS 'Fila principal de atuação do atendente.';
COMMENT ON COLUMN CRM_ATENDENTE.USUARIO_SICS_REF  IS 'Vínculo com o cadastro de usuário no SICS.';

CREATE INDEX IX_ATENDENTE_FILA ON CRM_ATENDENTE (FILA_PRINCIPAL_ID);

--------------------------------------------------------------------------------
-- 5) CRM_CHAMADO — o card do funil (centro do modelo)
--------------------------------------------------------------------------------
CREATE TABLE CRM_CHAMADO (
    ID                   NUMBER GENERATED BY DEFAULT ON NULL AS IDENTITY PRIMARY KEY,
    PROTOCOLO            VARCHAR2(30)  NOT NULL,
    ASSUNTO              VARCHAR2(300) NOT NULL,
    DESCRICAO            CLOB,
    TIPO                 VARCHAR2(40),
    CATEGORIA            VARCHAR2(80),
    CANAL                VARCHAR2(40),
    PRIORIDADE           VARCHAR2(20)  DEFAULT 'MEDIA' NOT NULL,
    STATUS               VARCHAR2(20)  DEFAULT 'NOVO'  NOT NULL,
    MOTIVO_ENCERRAMENTO  VARCHAR2(300),
    CONTATO_ID           NUMBER        NOT NULL,
    FILA_ID              NUMBER,
    ATENDENTE_ID         NUMBER,
    SLA_ID               NUMBER,
    ORIGEM_REF           VARCHAR2(120),
    -- prazos e marcos (SLA)
    ABERTO_EM            TIMESTAMP     DEFAULT SYSTIMESTAMP NOT NULL,
    PRAZO_PRIMEIRA_RESP  TIMESTAMP,
    PRAZO_RESOLUCAO      TIMESTAMP,
    PRIMEIRA_RESP_EM     TIMESTAMP,
    RESOLVIDO_EM         TIMESTAMP,
    FECHADO_EM           TIMESTAMP,
    SATISFACAO_NOTA      NUMBER(1),
    ATUALIZADO_EM        TIMESTAMP     DEFAULT SYSTIMESTAMP NOT NULL,
    CONSTRAINT UQ_CHAMADO_PROTOCOLO UNIQUE (PROTOCOLO),
    CONSTRAINT CK_CHAMADO_PRIORIDADE CHECK (PRIORIDADE IN ('BAIXA','MEDIA','ALTA','URGENTE')),
    CONSTRAINT CK_CHAMADO_STATUS CHECK (STATUS IN
        ('NOVO','CLASSIFICADO','EM_ATENDIMENTO','AGUARDANDO',
         'RESOLVIDO','FECHADO','REABERTO','CANCELADO')),
    CONSTRAINT CK_CHAMADO_SATISFACAO CHECK (SATISFACAO_NOTA BETWEEN 1 AND 5),
    CONSTRAINT FK_CHAMADO_CONTATO   FOREIGN KEY (CONTATO_ID)   REFERENCES CRM_CONTATO   (ID),
    CONSTRAINT FK_CHAMADO_FILA      FOREIGN KEY (FILA_ID)      REFERENCES CRM_FILA      (ID),
    CONSTRAINT FK_CHAMADO_ATENDENTE FOREIGN KEY (ATENDENTE_ID) REFERENCES CRM_ATENDENTE (ID),
    CONSTRAINT FK_CHAMADO_SLA       FOREIGN KEY (SLA_ID)       REFERENCES CRM_SLA       (ID)
);

COMMENT ON TABLE  CRM_CHAMADO                     IS 'Chamado — o card do funil de atendimento.';
COMMENT ON COLUMN CRM_CHAMADO.PROTOCOLO           IS 'Protocolo único do chamado.';
COMMENT ON COLUMN CRM_CHAMADO.STATUS              IS 'NOVO, CLASSIFICADO, EM_ATENDIMENTO, AGUARDANDO, RESOLVIDO, FECHADO, REABERTO, CANCELADO.';
COMMENT ON COLUMN CRM_CHAMADO.ORIGEM_REF          IS 'Referência de origem (Dossiê/Contrato...).';
COMMENT ON COLUMN CRM_CHAMADO.MOTIVO_ENCERRAMENTO IS 'Motivo de fechamento ou cancelamento.';
COMMENT ON COLUMN CRM_CHAMADO.SATISFACAO_NOTA     IS 'Nota de satisfação 1-5 pós-atendimento.';

CREATE INDEX IX_CHAMADO_STATUS    ON CRM_CHAMADO (STATUS);
CREATE INDEX IX_CHAMADO_FILA      ON CRM_CHAMADO (FILA_ID);
CREATE INDEX IX_CHAMADO_ATENDENTE ON CRM_CHAMADO (ATENDENTE_ID);
CREATE INDEX IX_CHAMADO_CONTATO   ON CRM_CHAMADO (CONTATO_ID);
CREATE INDEX IX_CHAMADO_ABERTO_EM ON CRM_CHAMADO (ABERTO_EM);

--------------------------------------------------------------------------------
-- 6) CRM_INTERACAO — linha do tempo de mensagens e notas
--------------------------------------------------------------------------------
CREATE TABLE CRM_INTERACAO (
    ID                   NUMBER GENERATED BY DEFAULT ON NULL AS IDENTITY PRIMARY KEY,
    CHAMADO_ID           NUMBER NOT NULL,
    TIPO                 VARCHAR2(20) DEFAULT 'MENSAGEM' NOT NULL,
    MENSAGEM             CLOB   NOT NULL,
    AUTOR_CONTATO_ID     NUMBER,
    AUTOR_ATENDENTE_ID   NUMBER,
    VISIVEL_SOLICITANTE  CHAR(1 CHAR) DEFAULT 'S' NOT NULL,
    CRIADO_EM            TIMESTAMP    DEFAULT SYSTIMESTAMP NOT NULL,
    CONSTRAINT CK_INTERACAO_TIPO    CHECK (TIPO IN ('MENSAGEM','NOTA_INTERNA')),
    CONSTRAINT CK_INTERACAO_VISIVEL CHECK (VISIVEL_SOLICITANTE IN ('S','N')),
    CONSTRAINT CK_INTERACAO_AUTOR   CHECK (
        (AUTOR_CONTATO_ID IS NOT NULL AND AUTOR_ATENDENTE_ID IS NULL) OR
        (AUTOR_CONTATO_ID IS NULL     AND AUTOR_ATENDENTE_ID IS NOT NULL)),
    CONSTRAINT FK_INTERACAO_CHAMADO   FOREIGN KEY (CHAMADO_ID)
        REFERENCES CRM_CHAMADO (ID) ON DELETE CASCADE,
    CONSTRAINT FK_INTERACAO_CONTATO   FOREIGN KEY (AUTOR_CONTATO_ID)   REFERENCES CRM_CONTATO   (ID),
    CONSTRAINT FK_INTERACAO_ATENDENTE FOREIGN KEY (AUTOR_ATENDENTE_ID) REFERENCES CRM_ATENDENTE (ID)
);

COMMENT ON TABLE  CRM_INTERACAO                     IS 'Linha do tempo de interações do chamado.';
COMMENT ON COLUMN CRM_INTERACAO.TIPO                IS 'MENSAGEM (visível) ou NOTA_INTERNA.';
COMMENT ON COLUMN CRM_INTERACAO.VISIVEL_SOLICITANTE IS 'S = o solicitante vê a interação; N = interna.';

CREATE INDEX IX_INTERACAO_CHAMADO ON CRM_INTERACAO (CHAMADO_ID, CRIADO_EM);

--------------------------------------------------------------------------------
-- 7) CRM_STATUS_HIST — métricas do funil (de -> para)
--------------------------------------------------------------------------------
CREATE TABLE CRM_STATUS_HIST (
    ID                NUMBER GENERATED BY DEFAULT ON NULL AS IDENTITY PRIMARY KEY,
    CHAMADO_ID        NUMBER       NOT NULL,
    STATUS_DE         VARCHAR2(20),
    STATUS_PARA       VARCHAR2(20) NOT NULL,
    ATENDENTE_ID      NUMBER,
    SEGUNDOS_NA_ETAPA NUMBER,
    MUDADO_EM         TIMESTAMP    DEFAULT SYSTIMESTAMP NOT NULL,
    CONSTRAINT FK_STATUSHIST_CHAMADO   FOREIGN KEY (CHAMADO_ID)
        REFERENCES CRM_CHAMADO (ID) ON DELETE CASCADE,
    CONSTRAINT FK_STATUSHIST_ATENDENTE FOREIGN KEY (ATENDENTE_ID) REFERENCES CRM_ATENDENTE (ID)
);

COMMENT ON TABLE  CRM_STATUS_HIST                   IS 'Histórico de mudanças de status (métricas do funil).';
COMMENT ON COLUMN CRM_STATUS_HIST.SEGUNDOS_NA_ETAPA IS 'Tempo (segundos) que o chamado ficou no STATUS_DE antes da mudança.';

CREATE INDEX IX_STATUSHIST_CHAMADO ON CRM_STATUS_HIST (CHAMADO_ID, MUDADO_EM);

--------------------------------------------------------------------------------
-- 8) CRM_ANEXO — arquivos ligados ao chamado
--------------------------------------------------------------------------------
CREATE TABLE CRM_ANEXO (
    ID            NUMBER GENERATED BY DEFAULT ON NULL AS IDENTITY PRIMARY KEY,
    CHAMADO_ID    NUMBER        NOT NULL,
    INTERACAO_ID  NUMBER,
    NOME          VARCHAR2(260) NOT NULL,
    URL           VARCHAR2(1000) NOT NULL,
    TIPO_MIME     VARCHAR2(120),
    TAMANHO_BYTES NUMBER,
    CRIADO_EM     TIMESTAMP     DEFAULT SYSTIMESTAMP NOT NULL,
    CONSTRAINT FK_ANEXO_CHAMADO   FOREIGN KEY (CHAMADO_ID)
        REFERENCES CRM_CHAMADO (ID) ON DELETE CASCADE,
    CONSTRAINT FK_ANEXO_INTERACAO FOREIGN KEY (INTERACAO_ID)
        REFERENCES CRM_INTERACAO (ID) ON DELETE SET NULL
);

COMMENT ON TABLE  CRM_ANEXO           IS 'Anexos (arquivos) ligados a um chamado e opcionalmente a uma interação.';
COMMENT ON COLUMN CRM_ANEXO.URL       IS 'Localização do arquivo (URL/Object Storage).';
COMMENT ON COLUMN CRM_ANEXO.TIPO_MIME IS 'Tipo MIME do arquivo.';

CREATE INDEX IX_ANEXO_CHAMADO ON CRM_ANEXO (CHAMADO_ID);

